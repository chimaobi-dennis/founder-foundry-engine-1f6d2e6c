#!/usr/bin/env node
// Builds supabase/dashboard/ai-gateway.single.ts from the multi-file edge
// function so it can be pasted into the Supabase dashboard editor, which
// takes one file. Run after changing anything under supabase/functions/.
//   node scripts/bundle-ai-gateway.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");

const cors = read("supabase/functions/_shared/cors.ts");
const pricing = read("supabase/functions/_shared/pricing.ts");
const providers = read("supabase/functions/_shared/providers.ts").replace(/^import .* from "\.\/pricing\.ts";\n/m, "");
let index = read("supabase/functions/ai-gateway/index.ts");

// Drop the local imports; keep the remote (deno.land / esm.sh) ones.
index = index
  .replace(/^import \{ corsHeaders, json \} from "\.\.\/_shared\/cors\.ts";\n/m, "")
  .replace(/^import \{ callProvider, ProviderError, type ChatMessage, type ProviderConfig \} from "\.\.\/_shared\/providers\.ts";\n/m, "")
  .replace(/^import \{\n[^}]*\} from "\.\.\/_shared\/pricing\.ts";\n/m, "");
if (index.includes("_shared")) throw new Error("unresolved _shared import in ai-gateway/index.ts");

const lines = index.split("\n");
const remote = lines.filter((l) => l.startsWith("import "));
const body = lines.filter((l) => !l.startsWith("import ")).join("\n");

const bundle = [
  "// Single-file build of supabase/functions/ai-gateway for pasting into the",
  "// Supabase dashboard (Edge Functions → Deploy a new function → via editor).",
  "// Generated by scripts/bundle-ai-gateway.mjs — edit the multi-file source,",
  "// not this file.",
  "",
  ...remote,
  "",
  "// ───── _shared/cors.ts ─────",
  cors,
  "// ───── _shared/pricing.ts ─────",
  pricing,
  "// ───── _shared/providers.ts ─────",
  providers,
  "// ───── ai-gateway/index.ts ─────",
  body,
].join("\n");

mkdirSync(join(root, "supabase/dashboard"), { recursive: true });
writeFileSync(join(root, "supabase/dashboard/ai-gateway.single.ts"), bundle);
console.log(`wrote supabase/dashboard/ai-gateway.single.ts (${bundle.split("\n").length} lines)`);
